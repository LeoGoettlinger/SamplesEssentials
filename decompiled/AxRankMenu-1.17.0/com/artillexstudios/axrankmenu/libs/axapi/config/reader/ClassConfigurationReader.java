   public ClassConfigurationReader(Yaml yaml, YamlConstructor constructor, TypeAdapterHolder holder, KeyRenamer renamer, Class<?> clazz) {
      this.holder = holder;
      this.constructor = constructor;
      this.renamer = renamer;
      this.clazz = clazz;
      this.yaml = yaml;
   }

