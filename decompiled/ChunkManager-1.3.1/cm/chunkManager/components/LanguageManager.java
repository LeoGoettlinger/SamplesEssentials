   private void saveLanguageFile(String langCode, Map<String, String> defaults) {
      File langFile = new File(this.plugin.getDataFolder(), "lang/" + langCode + ".yml");
      langFile.getParentFile().mkdirs();
      YamlConfiguration config;
      if (langFile.exists()) {
         config = YamlConfiguration.loadConfiguration(langFile);
      } else {
         config = new YamlConfiguration();
      }

      boolean changed = false;

      for (Entry<String, String> entry : defaults.entrySet()) {
         if (!config.contains(entry.getKey())) {
            config.set(entry.getKey(), entry.getValue());
            changed = true;
         }
      }

      if (changed) {
         try {
            config.save(langFile);
         } catch (IOException var8) {
            this.plugin.getLogger().warning("Failed to save language file: " + langCode);
         }
      }
   }

